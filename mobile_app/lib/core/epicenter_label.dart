final Map<String, String> _labels = <String, String>{};

String epicenterLabel(
  String? original,
  double? latitude,
  double? longitude, {
  String? sourceId,
  String? countryCode,
}) {
  final String key = '$original|$latitude|$longitude|$sourceId|$countryCode';
  final String? cached = _labels[key];
  if (cached != null) return cached;
  final String label = _resolveEpicenter(
    original,
    latitude,
    longitude,
    sourceId: sourceId,
    countryCode: countryCode,
  );
  if (_labels.length >= 1000) _labels.remove(_labels.keys.first);
  _labels[key] = label;
  return label;
}

String _resolveEpicenter(
  String? original,
  double? latitude,
  double? longitude, {
  String? sourceId,
  String? countryCode,
}) {
  if (latitude != null &&
      longitude != null &&
      latitude.isFinite &&
      longitude.isFinite &&
      latitude.abs() <= 90 &&
      longitude.abs() <= 180) {
    if (latitude >= -4.5 &&
        latitude <= 13.8 &&
        longitude >= -82 &&
        longitude <= -66) {
      List<Object>? nearest;
      double best = double.infinity;
      final double p = latitude * math.pi / 180;
      for (final List<Object> town in colombiaPlaces) {
        final double q = (town[2] as num).toDouble() * math.pi / 180;
        final double d = (longitude - (town[3] as num)) * math.pi / 180;
        final double h =
            math.pow(math.sin((p - q) / 2), 2).toDouble() +
            math.cos(p) * math.cos(q) * math.pow(math.sin(d / 2), 2).toDouble();
        final double distance =
            12742.0176 * math.asin(math.sqrt(h.clamp(0, 1)));
        if (distance < best) {
          best = distance;
          nearest = town;
        }
      }
      // Borders/offshore: never infer Colombian jurisdiction from proximity alone.
      if (nearest != null &&
          best <=
              (countryCode == 'CO' || sourceId == 'sgc_colombia' ? 120 : 30)) {
        final String town = '${nearest[0]}, ${nearest[1]}';
        if (best < 3) return town;
        final double q = (nearest[2] as num).toDouble() * math.pi / 180;
        final double d = (longitude - (nearest[3] as num)) * math.pi / 180;
        final double bearing =
            (math.atan2(
                      math.sin(d) * math.cos(p),
                      math.cos(q) * math.sin(p) -
                          math.sin(q) * math.cos(p) * math.cos(d),
                    ) *
                    180 /
                    math.pi +
                360) %
            360;
        const List<String> compass = [
          'N',
          'NNE',
          'NE',
          'ENE',
          'E',
          'ESE',
          'SE',
          'SSE',
          'S',
          'SSO',
          'SO',
          'OSO',
          'O',
          'ONO',
          'NO',
          'NNO',
        ];
        return '${best.round()} km al ${compass[((bearing + 11.25) / 22.5).floor() % 16]} de $town';
      }
    }
    if (original == null ||
        original.trim().isEmpty ||
        original.startsWith('Zona técnica')) {
      return 'Epicentro aproximado: ${latitude.toStringAsFixed(2)}, ${longitude.toStringAsFixed(2)}';
    }
  }
  final String text = (original ?? '').trim().replaceAll(RegExp(r'\s+'), ' ');
  if (text.isEmpty || text.startsWith('Zona técnica')) {
    return 'Epicentro en revisión';
  }
  final RegExpMatch? match = RegExp(
    r'^(\d+(?:\.\d+)?)\s*km\s+([NSEW]{1,3})\s+of\s+(.+)$',
    caseSensitive: false,
  ).firstMatch(text);
  if (match != null) {
    final String direction = match[2]!.toUpperCase().replaceAll('W', 'O');
    return '${double.parse(match[1]!).round()} km al $direction de ${match[3]}';
  }
  if (text.toLowerCase().startsWith('near ')) {
    return 'Cerca de ${text.substring(5)}';
  }
  final String normalized = text.replaceAll(RegExp(r'\s+[-–]\s+'), ', ');
  return normalized == normalized.toUpperCase()
      ? normalized
            .toLowerCase()
            .split(' ')
            .map((w) => w.isEmpty ? w : w[0].toUpperCase() + w.substring(1))
            .join(' ')
      : normalized;
}
